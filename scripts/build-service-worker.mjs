#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
/**
 * Bundle the offline-manifest service worker.
 *
 * `public/manifest-sw.js` used to be hand-written static JavaScript, which is
 * why it could not import anything — and that single limitation is what kept
 * the worker from writing the encrypted offline snapshot, flushing pending
 * roll-call events, or doing anything else useful with no page open (ADR
 * 20260804-manifest-web-push). Duplicating `offline-manifest-store.ts` into it
 * was never acceptable: two implementations of an encrypted safety-critical
 * record, kept in lockstep by hand.
 *
 * So the worker is now TypeScript that imports the real store, bundled here to
 * the same public path. The output is a **classic** worker script, not an ES
 * module: module service workers are not supported everywhere we care about,
 * and iOS Safari is exactly the platform with the fewest alternatives.
 *
 * Run before every build (`pnpm dev`, `pnpm build`, `pnpm e2e:build`); the
 * output is generated and gitignored.
 *
 * **Two passes.** The first, before `next build`, bundles the worker with no
 * asset list (`__OFFLINE_SHELL_ASSETS__` is `null`: dev, where chunk names are
 * not immutable and nothing is precached but the shell). The second, `--assets`
 * after `next build`, rebundles with the offline shell's asset list read from
 * that build's output (`scripts/offline-shell-assets.mjs`) and throws if the
 * list is empty or lacks the shell route's chunks. Passing `--assets` without a
 * build fails the build; it never reads a stale `.next` because the pipeline
 * runs it only straight after `next build`.
 */
import { build } from "esbuild";
import { collectOfflineShellAssets } from "./offline-shell-assets.mjs";

const ROOT = process.cwd();
const ENTRY = path.join(ROOT, "src/worker/manifest-sw.ts");
const OUT = path.join(ROOT, "public/manifest-sw.js");

const withAssets = process.argv.includes("--assets");
const assets = withAssets ? collectOfflineShellAssets(path.join(ROOT, ".next")) : null;
if (assets && assets.length === 0) throw new Error("offline shell assets: the list is empty");

const result = await build({
  entryPoints: [ENTRY],
  outfile: OUT,
  bundle: true,
  format: "iife",
  target: "es2022",
  platform: "browser",
  // Readable rather than minified on purpose: this file ships to a captain's
  // phone and is the thing anyone debugging a boat's offline copy will read in
  // devtools. It is ~15 KB either way.
  minify: false,
  sourcemap: false,
  legalComments: "none",
  define: {
    // The explicit, build-generated precache list; `null` outside a production build.
    __OFFLINE_SHELL_ASSETS__: JSON.stringify(assets),
    // `src/lib/clock.ts` reads these. In a worker there is no `process`, and
    // the honest value is "unset": the clock override is an e2e-harness
    // concern and a worker must always use the live clock, exactly as the
    // browser bundle does.
    "process.env.DIVEDAY_CLOCK": "undefined",
    "process.env.DATABASE_URL": "undefined",
    "process.env.NODE_ENV": JSON.stringify(process.env.NODE_ENV ?? "production"),
  },
  logLevel: "warning",
});

if (result.errors.length > 0) process.exit(1);

// A banner the next person opening devtools on a boat needs, since the file
// they are looking at is no longer the file anyone edits.
const bundled = await readFile(OUT, "utf8");
await writeFile(
  OUT,
  `// Generated by scripts/build-service-worker.mjs — do not edit.\n` +
    `// Source: src/worker/manifest-sw.ts\n${bundled}`,
  "utf8",
);

console.log(
  `service worker: built ${path.relative(ROOT, OUT)}` +
    (assets ? ` with ${assets.length} offline shell assets` : ""),
);
