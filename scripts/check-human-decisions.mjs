// Human decisions are named like ADRs: `H-YYYYMMDD-slug`, one file each, with a generated index.
//
// Until 2026-11-01 they were numbered (H-20260730-jurisdiction-waiver-text-medical … H-20261024-site-change-on-the) and the register was the top conflict
// file in 15 of 72 conflicting merges: two threads each took the next number, and twice
// (H-20261014-seat-is-the-word to H-20261014-course-session-price, renamed H-20261013-cancelling-a-run-refunds to H-20261015-crew-see-tips-on on 2026-10-22) the numbers collided outright. The
// date is the day the call was made and the slug is a few words of its question, so two
// threads adding a decision cannot take the same id.
//
// This guard fails on:
//   - a decision file whose name is not `H-YYYYMMDD-slug.md`, whose heading names another id,
//     whose id another file also claims, or that has no `**Status:**` line;
//   - an old-style `H-<number>` id anywhere in a tracked text file;
//   - a dangling citation: a date-slug id that names no decision file;
//   - an index in `docs/product/human-decisions/README.md` that differs from the files.
//
//   node scripts/check-human-decisions.mjs            check
//   node scripts/check-human-decisions.mjs --write    rewrite the index table (pnpm regen)
//
// The index sits between two marker comments and nothing else in the README is touched. On a
// merge conflict inside it, take either side and run `--write` again, never merge rows by hand.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { readBounded, SUBPROCESS_TIMEOUTS } from "./subprocess.mjs";

export const DECISIONS_DIR = "docs/product/human-decisions";
export const START =
  "<!-- human-decision-index:start (generated by node scripts/check-human-decisions.mjs --write) -->";
export const END = "<!-- human-decision-index:end -->";

/** The id shape, for building other patterns. */
export const ID_SOURCE = "H-\\d{8}-[a-z0-9]+(?:-[a-z0-9]+)*";
const ID_ONLY = new RegExp(`^${ID_SOURCE}$`);
const CITATION = new RegExp(ID_SOURCE, "g");
const OLD_STYLE = /\bH-\d{1,3}\b/g;

/** Files that must name made-up ids to test this guard and its renamer. */
const SELF = new Set([
  "scripts/check-human-decisions.test.mjs",
  "scripts/rename-human-decision-ids.mjs",
  "scripts/rename-human-decision-ids.test.mjs",
  "scripts/human-decision-ids.json",
]);
const SKIP_EXTENSIONS = /\.(png|jpe?g|gif|webp|avif|ico|woff2?|ttf|pdf|zip|gz|mp4|webm|mov|lock)$/i;

/** Every decision file name in the directory, sorted: everything but the README. */
export function decisionFileNames(dir) {
  return readdirSync(dir)
    .filter((name) => name.endsWith(".md") && name !== "README.md")
    .sort();
}

const newestDate = (text) =>
  [...text.matchAll(/\b(\d{4})-(\d{2})-(\d{2})\b/g)]
    .filter((m) => Number(m[2]) >= 1 && Number(m[2]) <= 12 && Number(m[3]) >= 1)
    .map((m) => m[0])
    .sort()
    .at(-1) ?? null;

/** `{ id, status, last, title }` from one decision file. */
export function decisionSummary(filename, contents) {
  return {
    id: filename.replace(/\.md$/, ""),
    status: contents.match(/^(?:- )?\*\*Status:\*\*\s*(.+?)\s*$/m)?.[1] ?? "",
    last: newestDate(contents),
    title: contents.match(/^#\s+\S+?:\s+(.+)$/m)?.[1]?.trim() ?? "",
  };
}

const cell = (text) => text.replace(/\\/g, "\\\\").replace(/\|/g, "\\|");

/** The index table, header included, one line per decision, sorted by id. */
export function indexTable(summaries) {
  const rows = [...summaries]
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .map((s) => `| ${s.id} | ${cell(s.status)} | ${s.last ?? "—"} | ${cell(s.title)} |`);
  return ["| ID | Status | Last dated | Decision |", "| --- | --- | --- | --- |", ...rows].join(
    "\n",
  );
}

/** The README with `table` between its markers, or null when a marker is missing. */
export function withIndex(readme, table) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) return null;
  return `${readme.slice(0, start + START.length)}\n\n${table}\n\n${readme.slice(end)}`;
}

/** Problems with the decision files themselves. `files` is `[{ name, contents }]`. */
export function decisionProblems(files) {
  const problems = [];
  const claimed = new Map();
  for (const { name, contents } of files) {
    const id = name.replace(/\.md$/, "");
    if (!ID_ONLY.test(id)) {
      problems.push(`${name}: not a date-slug id (expected H-YYYYMMDD-slug.md)`);
      continue;
    }
    const heading = contents.match(/^#\s+(\S+?):/m)?.[1];
    if (heading !== id) {
      problems.push(`${name}: the heading names ${heading ?? "no id"}, not ${id}`);
    }
    claimed.set(heading ?? id, [...(claimed.get(heading ?? id) ?? []), name]);
    if (!/^(?:- )?\*\*Status:\*\*\s*\S/m.test(contents)) {
      problems.push(`${name}: no "**Status:**" line`);
    }
  }
  for (const [id, names] of claimed) {
    if (names.length > 1) problems.push(`duplicate id ${id}: ${names.join(", ")}`);
  }
  return problems;
}

/**
 * Old-style and dangling citations. `lines` is `[{ file, line?, text }]`; `known` is the set
 * of decision ids. A cited token may carry trailing slug words ("H-…-slug-style"): it
 * resolves when a known id is the token or a hyphen-bounded prefix of it.
 */
export function citationProblems(lines, known) {
  const problems = [];
  const where = (row) => (row.line ? `${row.file}:${row.line}` : row.file);
  for (const row of lines) {
    for (const match of row.text.matchAll(OLD_STYLE)) {
      problems.push(
        `${where(row)}: old-style id ${match[0]} — human decisions are H-YYYYMMDD-slug now (node scripts/rename-human-decision-ids.mjs)`,
      );
    }
    for (const match of row.text.matchAll(CITATION)) {
      const token = match[0];
      const resolves = [...known].some((id) => token === id || token.startsWith(`${id}-`));
      if (!resolves)
        problems.push(`${where(row)}: dangling citation ${token} names no decision file`);
    }
  }
  return problems;
}

/** Tracked text files as `[{ file, line, text }]`, one per line that could cite an id. */
export function trackedLines(root) {
  const listed = readBounded("git", ["ls-files", "-z"], {
    cwd: root,
    encoding: "utf8",
    timeoutMs: SUBPROCESS_TIMEOUTS.git,
    maxBuffer: 64 * 1024 * 1024,
  });
  const rows = [];
  for (const file of listed.split("\0").filter(Boolean)) {
    if (SELF.has(file) || SKIP_EXTENSIONS.test(file)) continue;
    const absolute = path.join(root, file);
    if (!existsSync(absolute)) continue;
    let text;
    try {
      text = readFileSync(absolute, "utf8");
    } catch {
      continue;
    }
    if (text.includes("\0") || !/H-\d/.test(text)) continue;
    text.split("\n").forEach((line, index) => {
      if (/H-\d/.test(line)) rows.push({ file, line: index + 1, text: line });
    });
  }
  return rows;
}

function main() {
  const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
  const dir = path.join(root, DECISIONS_DIR);
  const names = decisionFileNames(dir);
  const files = names.map((name) => ({
    name,
    contents: readFileSync(path.join(dir, name), "utf8"),
  }));
  const summaries = files.map((f) => decisionSummary(f.name, f.contents));
  const readmePath = path.join(dir, "README.md");
  const readme = readFileSync(readmePath, "utf8");
  const expected = withIndex(readme, indexTable(summaries));

  if (process.argv.includes("--write")) {
    if (expected === null) {
      console.error(`${DECISIONS_DIR}/README.md has no ${START} … ${END} block to fill.`);
      process.exit(1);
    }
    if (expected !== readme) writeFileSync(readmePath, expected);
    console.log("human-decisions: README.md index written");
    return;
  }

  const failures = decisionProblems(files);
  if (expected === null) {
    failures.push(
      "README.md: the generated index block (human-decision-index:start … :end) is missing",
    );
  } else if (expected !== readme) {
    failures.push(
      "README.md: the index table is stale — run `node scripts/check-human-decisions.mjs --write` (on a merge conflict in the table, take either side and run it again)",
    );
  }
  failures.push(...citationProblems(trackedLines(root), new Set(summaries.map((s) => s.id))));

  if (failures.length > 0) {
    console.error(`Human decision ids failed:\n${failures.map((item) => `- ${item}`).join("\n")}`);
    process.exit(1);
  }
  console.log(
    `human-decisions: ${names.length} decisions, ids unique, citations resolve, index current`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
