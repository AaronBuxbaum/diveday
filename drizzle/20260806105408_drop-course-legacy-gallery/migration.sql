-- Both halves land in one release, and that is a deliberate departure from the runbook, not an
-- oversight. The four-step rename table in docs/engineering/deploy-and-migrations-runbook.md puts
-- "stops writing" and "drop" together in release 4; the caveat directly under it says the drop must
-- land only after every running instance has stopped touching the column, "including the deployment
