-- production build while the previous release is still serving, so this release resolves the
-- tension by accepting the cost rather than by splitting into two deploys.
--
-- What that costs, measured rather than assumed. Drizzle's `db.select().from(courses)` compiles to
-- an explicit column list, not `SELECT *`, so the previous release names `image_urls` and
-- `image_alts` in its *reads* as well as its writes. For the length of the deploy, every one of
-- these fails on the previous release with `column courses.image_urls does not exist`:
--
--   * the public course catalog and course page (`listActiveCourses`, `getCourseBySlug`);
--   * the staff course roster and editor (`listCourses`, `pagedCourses`, `getCourseBySlug`);
--   * booking or claiming a seat on a course session, and creating a course departure
--     (`bookSpot` and `createBookingRecord` in src/db/bookings.ts, src/db/seat-claims.ts,
--     src/db/trips-create.ts — each loads the course row whenever a trip has a `course_id`);
--   * the CSV export bundle and the weekly backup export (`loadShopExportBundleInput`).
--
-- Surfaces that never touch `courses` are unaffected, as is anything selecting named columns
-- (`hasActiveCourses`, the ⌘K search arm) — but the diver-facing course funnel is not a
-- write-only path, and this window is larger than "a course edit fails".
--
-- Second accepted cost: Instant Rollback to the previous release stops being safe the moment this
-- applies, because that deployment would then be permanently broken in the ways above rather than
-- briefly. Rolling back past this release means a forward migration or branching Neon from a
